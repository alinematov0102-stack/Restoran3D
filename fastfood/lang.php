function t(string $key): string {
    $lang = $_COOKIE['ff_lang'] ?? 'uz';
    if (!isset($GLOBALS['ff_translations'][$lang])) {
        $lang = 'uz';
    }
    return $GLOBALS['ff_translations'][$lang][$key] ?? $GLOBALS['ff_translations']['uz'][$key] ?? $key;
}

function ff_current_lang(): string {
    $lang = $_COOKIE['ff_lang'] ?? 'uz';
    return in_array($lang, ['uz', 'ru', 'en']) ? $lang : 'uz';
}
